#[test]
fn dotted_byte_names_preserve_recovered_labels_without_relaxing_ascii_api() {
    let name = Name::from_dotted_bytes(b"l\xffase.example.").unwrap();
    assert_eq!(name.as_wire(), b"\x05l\xffase\x07example\0");
    assert_eq!(name.dnsmasq_bytes(), b"l\xffase.example");
    assert_eq!(Name::from_ascii("lÿase"), Err(WireError::InvalidName));
    assert_eq!(
        Name::from_dotted_bytes(b"a..example"),
        Err(WireError::InvalidName)
    );
    assert_eq!(
        Name::from_dotted_bytes(&[b'x'; 64]),
        Err(WireError::InvalidName)
    );
    assert_eq!(Name::from_dotted_bytes(b"."), Ok(Name::root()));
}

// Synthetic independent DNS bytes. No expected packet is generated by the writer.
const A_RESPONSE: &[u8] = &[
    0x12, 0x34, 0x81, 0x80, 0, 1, 0, 1, 0, 0, 0, 0, 3, b'w', b'w', b'w', 7, b'e', b'x', b'a', b'm',
    b'p', b'l', b'e', 0, 0, 1, 0, 1, 0xc0, 0x0c, 0, 1, 0, 1, 0, 0, 0, 60, 0, 4, 192, 0, 2, 7,
];

#[test]
fn header_and_compressed_response() {
    let message = Message::parse(A_RESPONSE).unwrap();
    assert_eq!(message.header.id, 0x1234);
    assert_eq!(message.header.flags, 0x8180);
    assert_eq!(message.end, 45);
    let question = Question::parse(A_RESPONSE, 12).unwrap();
    assert_eq!(question.end, 29);
    assert_eq!(question.name.dnsmasq_bytes(), b"www.example");
    let answer = message.records(Section::Answer).next().unwrap();
    assert_eq!(answer.name().unwrap(), question.name);
    assert_eq!(answer.ttl, 60);
    assert_eq!(answer.rdata, &[192, 0, 2, 7]);
}

#[test]
fn record_section_replays_complete_answers_without_requiring_later_records() {
    let mut packet = A_RESPONSE.to_vec();
    packet[11] = 1;
    packet.push(0); // Additional owner without fixed fields.
    assert!(Message::parse(&packet).is_err());
    let (answers, end) = Records::parse_section(&packet, 29, 1).unwrap();
    assert_eq!(end, 45);
    for mut replay in [answers.clone(), answers] {
        let answer = replay.next().unwrap();
        assert_eq!(
            (answer.rrtype, answer.ttl, answer.rdata),
            (1, 60, &[192, 0, 2, 7][..])
        );
        assert!(replay.next().is_none());
    }
    assert!(Records::parse_section(&packet, 29, 2).is_err());
    assert!(Records::parse_section(&packet, packet.len() + 1, 0).is_err());
}

