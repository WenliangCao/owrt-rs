#!/usr/bin/env python3
"""Generate components/netifd/src/netdev_types.rs from <linux/if_arp.h>.

`system_add_devtype` falls back to an ARPHRD-number lookup when the device's
uevent has no DEVTYPE on its first line. The table's order matters: the lookup
is linear and the LAST entry is the default for an unknown number, so the order
is taken from system-linux.c rather than sorted.

  python3 tools/gen_netdev_types.py <path to linux/if_arp.h> \
      > components/netifd/src/netdev_types.rs
"""
import re
import sys

# the order in netdev_types[] in system-linux.c; the last entry is the default
ORDER = [
    ("NETROM", "netrom"), ("ETHER", "ethernet"), ("EETHER", "eethernet"),
    ("AX25", "ax25"), ("PRONET", "pronet"), ("CHAOS", "chaos"),
    ("IEEE802", "ieee802"), ("ARCNET", "arcnet"), ("APPLETLK", "appletlk"),
    ("DLCI", "dlci"), ("ATM", "atm"), ("METRICOM", "metricom"),
    ("IEEE1394", "ieee1394"), ("EUI64", "eui64"), ("INFINIBAND", "infiniband"),
    ("SLIP", "slip"), ("CSLIP", "cslip"), ("SLIP6", "slip6"),
    ("CSLIP6", "cslip6"), ("RSRVD", "rsrvd"), ("ADAPT", "adapt"),
    ("ROSE", "rose"), ("X25", "x25"), ("HWX25", "hwx25"), ("PPP", "ppp"),
    ("CISCO", "cisco"), ("LAPB", "lapb"), ("DDCMP", "ddcmp"),
    ("RAWHDLC", "rawhdlc"), ("TUNNEL", "tunnel"), ("TUNNEL6", "tunnel6"),
    ("FRAD", "frad"), ("SKIP", "skip"), ("LOOPBACK", "loopback"),
    ("LOCALTLK", "localtlk"), ("FDDI", "fddi"), ("BIF", "bif"),
    ("SIT", "sit"), ("IPDDP", "ipddp"), ("IPGRE", "ipgre"),
    ("PIMREG", "pimreg"), ("HIPPI", "hippi"), ("ASH", "ash"),
    ("ECONET", "econet"), ("IRDA", "irda"), ("FCPP", "fcpp"),
    ("FCAL", "fcal"), ("FCPL", "fcpl"), ("FCFABRIC", "fcfabric"),
    ("IEEE80211", "ieee80211"), ("IEEE80211_PRISM", "ie80211-prism"),
    ("IEEE80211_RADIOTAP", "ieee80211-radiotap"),
    ("PHONET", "phonet"), ("PHONET_PIPE", "phonet-pipe"),
    ("IEEE802154", "ieee802154"), ("VOID", "void"), ("NONE", "none"),
]

src = open(sys.argv[1]).read()
vals = {}
for name, val in re.findall(r'#define\s+ARPHRD_(\w+)\s+(\S+)', src):
    try:
        vals[name] = int(val, 0)
    except ValueError:
        pass

print('// @generated by tools/gen_netdev_types.py from <linux/if_arp.h>.')
print('// Do not edit by hand.')
print('//')
print('// The ARPHRD fallback for `devtype`, in system-linux.c\'s own order.')
print('// The lookup is linear and the last entry is the default, so both the')
print('// order and the final entry are part of the behaviour.')
print()
print('pub const NETDEV_TYPES: &[(u16, &str)] = &[')
missing = []
for name, label in ORDER:
    if name not in vals:
        missing.append(name)
        continue
    print(f'    ({vals[name]}, "{label}"),')
print('];')
if missing:
    print(f'\n// not defined in this header, and #ifdef-ed out in the C too: '
          f'{", ".join(missing)}', file=sys.stderr)
