pub fn ethtool_modes(modes_h: &str, ethtool_h: &str) -> Result<String> {
    let body = Regex::new(r"(?s)enum ethtool_link_mode_bit_indices \{(.*?)\n\};")?
        .captures(ethtool_h)
        .ok_or_else(|| Error::new("no ethtool_link_mode_bit_indices enum"))?[1]
        .to_owned();
    let mut bits = HashMap::new();
    let mut next = 0i64;
    for capture in Regex::new(r"(ETHTOOL_LINK_MODE_\w+)\s*(?:=\s*(\d+))?")?.captures_iter(&body) {
        if let Some(value) = capture.get(2) {
            next = value.as_str().parse()?;
        }
        bits.insert(capture[1].to_owned(), next);
        next += 1;
    }
    let bit = |speed: &str, mode: &str, duplex: &str| {
        let name = format!("ETHTOOL_LINK_MODE_{speed}base{mode}_{duplex}_BIT");
        bits.get(&name)
            .copied()
            .ok_or_else(|| Error::new(format!("{name} is not in <linux/ethtool.h>")))
    };
    let mut rows = Vec::new();
    for capture in Regex::new(r"ETHTOOL_MODE_(FULL|HALF|BOTH)\((\d+),\s*([A-Za-z0-9]+)\)")?
        .captures_iter(modes_h)
    {
        let (kind, speed, mode) = (&capture[1], &capture[2], &capture[3]);
        let half = if kind == "FULL" {
            -1
        } else {
            bit(speed, mode, "Half")?
        };
        let full = if kind == "HALF" {
            -1
        } else {
            bit(speed, mode, "Full")?
        };
        rows.push(format!(
            "    ({}, {half}, {full}, \"{speed}base{mode}\"),\n",
            speed.parse::<u64>()?
        ));
    }
    let pause = |name: &str| {
        bits.get(name)
            .copied()
            .ok_or_else(|| Error::new(format!("{name} is not in <linux/ethtool.h>")))
    };
    let mut out = String::from(
        "// @generated by `owrt-tools gen-ethtool-modes` from the OpenWrt 25.12.5\n\
         // aarch64 toolchain. Do not edit by hand.\n\
         //\n\
         // The same table netifd generates at build time: the names, and the\n\
         // order `network.device status` reports them in.\n\
         \n\
         /// (speed, half-duplex bit or -1, full-duplex bit or -1, name)\n\
         pub const ETHTOOL_MODES: &[(u32, i32, i32, &str)] = &[\n",
    );
    out.extend(rows);
    out.push_str("];\n\n");
    writeln!(
        out,
        "pub const ETHTOOL_LINK_MODE_PAUSE_BIT: i32 = {};",
        pause("ETHTOOL_LINK_MODE_Pause_BIT")?
    )
    .ok();
    writeln!(
        out,
        "pub const ETHTOOL_LINK_MODE_ASYM_PAUSE_BIT: i32 = {};",
        pause("ETHTOOL_LINK_MODE_Asym_Pause_BIT")?
    )
    .ok();
    Ok(out)
}

/// Python `int(text, 0)`: optional sign, `0x`/`0o`/`0b` prefixes, `_`
/// between digits, and no leading zeros on a nonzero decimal.
fn python_int(text: &str) -> Option<i64> {
    let (negative, digits) = match text.strip_prefix('-') {
        Some(rest) => (true, rest),
        None => (false, text.strip_prefix('+').unwrap_or(text)),
    };
    let lower = digits.to_ascii_lowercase();
    let (radix, body) = match lower.get(..2) {
        Some("0x") => (16, &lower[2..]),
        Some("0o") => (8, &lower[2..]),
        Some("0b") => (2, &lower[2..]),
        _ => (10, lower.as_str()),
    };
    let body = body
        .strip_prefix('_')
        .filter(|_| radix != 10)
        .unwrap_or(body);
    if body.is_empty() || body.starts_with('_') || body.ends_with('_') || body.contains("__") {
        return None;
    }
    let clean = body.replace('_', "");
    if radix == 10 && clean.len() > 1 && clean.starts_with('0') && clean.bytes().any(|b| b != b'0')
    {
        return None;
    }
    let value = i64::from_str_radix(&clean, radix).ok()?;
    Some(if negative { -value } else { value })
}

/// The table, plus the names this header lacks (reported on stderr).
pub fn netdev_types(if_arp_h: &str) -> Result<(String, Vec<&'static str>)> {
    let mut values = HashMap::new();
    for capture in Regex::new(r"#define\s+ARPHRD_(\w+)\s+(\S+)")?.captures_iter(if_arp_h) {
        if let Some(value) = python_int(&capture[2]) {
            values.insert(capture[1].to_owned(), value);
        }
    }
    let mut out = String::from(
        "// @generated by `owrt-tools gen-netdev-types` from <linux/if_arp.h>.\n\
         // Do not edit by hand.\n\
         //\n\
         // The ARPHRD fallback for `devtype`, in system-linux.c's own order.\n\
         // The lookup is linear and the last entry is the default, so both the\n\
         // order and the final entry are part of the behaviour.\n\
         \n\
         pub const NETDEV_TYPES: &[(u16, &str)] = &[\n",
    );
    let mut missing = Vec::new();
    for (name, label) in NETDEV_ORDER {
        match values.get(name) {
            Some(value) => writeln!(out, "    ({value}, \"{label}\"),")
                .map_err(|e| Error::new(e.to_string()))?,
            None => missing.push(name),
        }
    }
    out.push_str("];\n");
    Ok((out, missing))
}

pub fn ethtool_main(raw: &[String]) -> Result<i32> {
    let [modes, ethtool] = raw else {
        util::bail!("usage: gen-ethtool-modes MODES_H ETHTOOL_H")
    };
    print!(
        "{}",
        ethtool_modes(
            &util::read_text(Path::new(modes))?,
            &util::read_text(Path::new(ethtool))?
        )?
    );
    Ok(0)
}

pub fn netdev_main(raw: &[String]) -> Result<i32> {
    let [if_arp] = raw else {
        util::bail!("usage: gen-netdev-types IF_ARP_H")
    };
    let (table, missing) = netdev_types(&util::read_text(Path::new(if_arp))?)?;
    print!("{table}");
    if !missing.is_empty() {
        eprintln!(
            "\n// not defined in this header, and #ifdef-ed out in the C too: {}",
            missing.join(", ")
        );
    }
    Ok(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    const ETHTOOL_H: &str = "enum ethtool_link_mode_bit_indices {\n\tETHTOOL_LINK_MODE_10baseT_Half_BIT\t= 0,\n\
        \tETHTOOL_LINK_MODE_10baseT_Full_BIT\t= 1,\n\tETHTOOL_LINK_MODE_Pause_BIT\t= 13,\n\tETHTOOL_LINK_MODE_Asym_Pause_BIT,\n\
        \tETHTOOL_LINK_MODE_1000baseX_Full_BIT = 41,\n\t__ETHTOOL_LINK_MODE_MASK_NBITS\n};\n";

    #[test]
    fn ethtool_rows_keep_generator_order_and_implicit_bits() {
        let table = ethtool_modes(
            "ETHTOOL_MODE_FULL(1000, X)\nETHTOOL_MODE_BOTH(10, T)\n",
            ETHTOOL_H,
        )
        .unwrap();
        assert!(
            table.contains("    (1000, -1, 41, \"1000baseX\"),\n    (10, 0, 1, \"10baseT\"),\n];"),
            "{table}"
        );
        assert!(table.ends_with(
            "PAUSE_BIT: i32 = 13;\npub const ETHTOOL_LINK_MODE_ASYM_PAUSE_BIT: i32 = 14;\n"
        ));
        assert!(
            ethtool_modes("ETHTOOL_MODE_HALF(1000, X)\n", ETHTOOL_H).is_err(),
            "unknown bit"
        );
    }

    #[test]
    fn netdev_table_follows_c_order_and_python_int_parsing() {
        let (table, missing) = netdev_types(
            "#define ARPHRD_ETHER \t1\n#define ARPHRD_NETROM\t0\n#define ARPHRD_VOID 0xFFFF\n\
                                            #define ARPHRD_NONE 0xFFFE\n#define ARPHRD_PPP 010\n",
        )
        .unwrap();
        assert!(table.contains("    (0, \"netrom\"),\n    (1, \"ethernet\"),\n    (65535, \"void\"),\n    (65534, \"none\"),\n];"), "{table}");
        assert!(missing.contains(&"PPP") && missing.contains(&"EETHER"));
        assert_eq!(python_int("0x1_0"), Some(16));
        assert_eq!(python_int("-7"), Some(-7));
        assert_eq!(python_int("08"), None);
        assert_eq!(python_int("00"), Some(0));
        assert_eq!(python_int("(1)"), None);
    }
}
