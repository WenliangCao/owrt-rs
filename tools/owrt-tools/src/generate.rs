//! Generators for netifd's kernel-derived tables:
//!
//! `gen-ethtool-modes MODES_H ETHTOOL_H > components/netifd/src/ethtool_modes.rs`
//!
//! netifd builds its mode table at compile time with make_ethtool_modes_h.sh,
//! whose ordering inside one speed comes out of a `sort -g` pipeline and is
//! not alphabetical. `network.device status` reports the modes in that order,
//! so the order is taken from the generator's own output rather than
//! re-derived:
//!
//! ```sh
//! # on a host with the OpenWrt SDK for this target
//! sh netifd/make_ethtool_modes_h.sh "$CC" > ethtool-modes.h
//! ```
//!
//! `ETHTOOL_H` is the same toolchain's `<linux/ethtool.h>`, which supplies the
//! numeric bit indices the enum names stand for.
//!
//! `gen-netdev-types IF_ARP_H > components/netifd/src/netdev_types.rs`
//!
//! `system_add_devtype` falls back to an ARPHRD-number lookup when the
//! device's uevent has no DEVTYPE on its first line. The lookup is linear and
//! the LAST entry is the default for an unknown number, so the order is taken
//! from system-linux.c rather than sorted.

