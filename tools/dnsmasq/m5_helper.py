CAPTURE = r'''#!/bin/sh
if [ "$1" = init ]; then
  if [ "$M5_SLOW_INIT" = 1 ]; then
    : > "$M5_OUTPUT/init-sleeping"
    sleep 2
    : > "$M5_OUTPUT/init-finished"
  fi
  cat "$M5_OUTPUT/init.leases"
  exit "${M5_INIT_STATUS:-0}"
fi
count=0
[ ! -f "$M5_OUTPUT/count" ] || read -r count < "$M5_OUTPUT/count"
count=$((count + 1))
printf '%s\n' "$count" > "$M5_OUTPUT/count"
prefix="$M5_OUTPUT/$count"
printf '%s\0' "$@" > "$prefix.argv"
env -0 > "$prefix.env"
id -u > "$prefix.uid"
id -g > "$prefix.gid"
id -G > "$prefix.groups"
printf '%s\n' "$$" > "$prefix.pid"
date +%s > "$prefix.time"
readlink /proc/$$/fd/0 > "$prefix.stdin"
for f in /proc/$$/fd/*; do readlink "$f"; done > "$prefix.fds"
if [ "$M5_SLOW" = 1 ] && [ "$count" = 1 ]; then
  : > "$M5_OUTPUT/slow-ready"
  sleep "${M5_SLOW_SECONDS:-2}"
fi
if [ "$M5_LATE_OUTPUT" = 1 ]; then
  i=0
  while [ "$i" -lt 2048 ]; do
    echo 012345678901234567890123456789012345678901234567890123456789012345
    i=$((i + 1))
  done
  echo late-stderr >&2
fi
: > "$prefix.done"
if [ "$M5_REMOVE_SCRIPT" = 1 ] && [ "$count" = 1 ]; then rm "$0"; fi
if [ "$M5_EXIT" = 1 ]; then echo script-failed >&2; exit 7; fi
if [ "$M5_SIGNAL" = 1 ]; then kill -USR1 "$$"; fi
'''


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + '\n')


def wait(predicate, label, timeout=5):
    deadline = time.monotonic() + timeout
    last = None
    while time.monotonic() < deadline:
        try:
            result = predicate()
            if result:
                return result
        except (OSError, ValueError) as error:
            last = str(error)
        time.sleep(.01)
    raise AssertionError(f'{label} timed out: {last}')


def children(pid):
    pending, result = [pid], set()
    while pending:
        current = pending.pop()
        if current in result:
            continue
        result.add(current)
        try:
            pending.extend(map(int, Path(f'/proc/{current}/task/{current}/children').read_text().split()))
        except (OSError, ValueError):
            pass
    return result


def capture(folder):
    result = []
    for done in sorted(folder.glob('*.done'), key=lambda p: int(p.stem)):
        prefix = folder / done.stem
        args = prefix.with_suffix('.argv').read_bytes().split(b'\0')[:-1]
        env = {}
        for item in prefix.with_suffix('.env').read_bytes().split(b'\0'):
            key, sep, value = item.partition(b'=')
            if sep and key.startswith(b'DNSMASQ_'):
                env[key.decode('ascii')] = value.hex()
        result.append({'argv': [value.hex() for value in args], 'env': env,
                       'uid': int(prefix.with_suffix('.uid').read_text()),
                       'gid': int(prefix.with_suffix('.gid').read_text()),
                       'groups': sorted(map(int, prefix.with_suffix('.groups').read_text().split())),
                       'pid': int(prefix.with_suffix('.pid').read_text()),
                       'time': int(prefix.with_suffix('.time').read_text()),
                       'fds': prefix.with_suffix('.fds').read_text().splitlines(),
                       'stdin': prefix.with_suffix('.stdin').read_text().strip()})
    return result


def normalized(records, start, end):
    result = copy.deepcopy(records)
    for row in result:
        row.pop('pid'); row.pop('time')
        if row.get('stdin', '').startswith('pipe:'): row['stdin'] = 'pipe'
        elif row.get('stdin', '').startswith('socket:'): row['stdin'] = 'socket'
        # FDs include script/output files and vary by PID/implementation. The
        # service socket/pipe boundary is asserted independently below.
        row['fd_isolated'] = not any(value.startswith('socket:') or value.endswith('/leases') for value in row.pop('fds'))
        if not row['fd_isolated']:
            raise AssertionError('service socket/lease descriptor inherited by script')
        for key in ('DNSMASQ_LEASE_EXPIRES', 'DNSMASQ_TIME_REMAINING'):
            value = row['env'].get(key)
            if value is None:
                continue
            number = int(bytes.fromhex(value))
            if key == 'DNSMASQ_LEASE_EXPIRES':
                if number:
                    if not start + 598 <= number <= end + 602:
                        raise AssertionError(f'lease expiry outside request window: {number}')
                    row['env'][key] = 'finite-600-second-lease'
            elif not 598 <= number <= 600:
                raise AssertionError(f'helper snapshot remaining time outside 600-second lease: {number}')
            else:
                row['env'][key] = '600-seconds-with-one-second-boundaries'
    return result


class Side:
    def __init__(self, root, side, out, name, flags=(), env=None, debug=False):
        self.root, self.side, self.out, self.name = root, side, out, name
        self.folder = root / 'm2' / f'{side}-{name}'
        self.folder.mkdir(mode=0o777)
        self.folder.chmod(0o777)
        self.inside = '/m2/' + self.folder.name
        self.events = self.folder / 'events'
        self.events.mkdir(mode=0o777); self.events.chmod(0o777)
        self.script = self.folder / 'capture'
        self.script.write_text(CAPTURE); self.script.chmod(0o755)
        self.leasefile = self.folder / 'leases'
        self.config = self.folder / 'config'
        self.config.write_text('\n'.join([
            'no-hosts', 'no-resolv', 'no-ping', 'listen-address=127.0.0.1',
            'port=15353', 'host-record=helper.test,192.0.2.44', 'domain=lan',
            'dhcp-range=127.0.0.10,127.0.0.20,255.0.0.0,10m', 'dhcp-authoritative',
            'user=root', 'group=root', 'log-facility=-',
            f'dhcp-leasefile={self.inside}/leases', f'pid-file={self.inside}/pid',
            f'dhcp-script={self.inside}/capture', *flags]) + '\n')
        self.env = {**os.environ, 'LC_ALL': 'C', 'M5_OUTPUT': self.inside + '/events',
                    **(env or {})}
        self.debug = debug
        self.cli_flags = []
        self.process = None; self.log = None; self.client = None
        self.xid = 0; self.raw = []; self.stages = []; self.descendants = set()
        self.support = []
        self.start_epoch = time.time()
        self.init_dns_latency = None

    def start_hotplug(self):
        # Real image ubusd + procd register hotplug.dhcp; neither is mocked.
        hotplug = self.folder / 'hotplug'
        hotplug.mkdir()
        handler_dir = self.root / 'etc/hotplug.d/dhcp'
        handler_dir.mkdir(parents=True, exist_ok=True)
        handler = handler_dir / '00-m5-capture'
        handler.write_text("#!/bin/sh\ncount=0\n[ ! -f '{0}/count' ] || read -r count < '{0}/count'\ncount=$((count + 1))\nprintf '%s\\n' \"$count\" > '{0}/count'\nenv -0 > '{0}/'\"$count\"'.env'\n: > '{0}/'\"$count\"'.done'\n".format(self.inside + '/hotplug'))
        handler.chmod(0o755)
        self.env['USER_DHCPSCRIPT'] = self.inside + '/capture'
        self.config.write_text(self.config.read_text().replace('dhcp-script=' + self.inside + '/capture', 'dhcp-script=/usr/lib/dnsmasq/dhcp-script.sh'))
        for binary, obj in [('/sbin/ubusd', None), ('/sbin/procd', 'hotplug.dhcp')]:
            log = (self.out / f'{self.side}-{self.name}-{Path(binary).name}.log').open('wb')
            proc = subprocess.Popen(command(self.root, binary), stdout=log, stderr=log, start_new_session=True)
            self.support.append((proc, log))
            def ready():
                check = subprocess.run(command(self.root, '/bin/ubus', 'list', *([obj] if obj else [])), capture_output=True, timeout=1)
                return check.returncode == 0 and (obj is None or obj.encode() in check.stdout)
            wait(ready, binary)

    def hotplug_events(self):
        out = []
        folder = self.folder / 'hotplug'
        for path in sorted(folder.glob('*.done'), key=lambda p: int(p.stem)):
            row = {}
            for field in path.with_suffix('.env').read_bytes().split(b'\0'):
                key, sep, value = field.partition(b'=')
                if sep and (key.startswith(b'DNSMASQ_') or key in (b'ACTION', b'HOSTNAME', b'MACADDR', b'IPADDR')):
                    row[key.decode()] = value.hex()
            out.append(row)
        # Apply the identical time rules as direct helper capture.
        fake = [{'env': row, 'pid': 0, 'time': 0, 'fds': []} for row in out]
        return [row['env'] for row in normalized(fake, self.start_epoch, time.time())]

    def start(self):
        if self.name == 'hotplug':
            self.start_hotplug()
        self.log = (self.out / f'{self.side}-{self.name}.log').open('wb')
        args = ['--no-daemon' if self.debug else '--keep-in-foreground', '--conf-file=' + self.inside + '/config', *self.cli_flags]
        self.process = subprocess.Popen(command(self.root, self.side, *args),
                                        env=self.env, stdout=self.log, stderr=self.log,
                                        start_new_session=True)
        if self.name == 'slow-init':
            wait(lambda: (self.events / 'init-sleeping').exists(), 'init script sleeping')
            if self.side == 'rust':
                started = time.monotonic()
                wait(self.dns, 'DNS advances during init', timeout=.8)
                self.init_dns_latency = time.monotonic() - started
                if (self.events / 'init-finished').exists():
                    raise AssertionError('DNS did not advance until init completed')
        def ready():
            if self.process.poll() is not None:
                raise AssertionError(f'{self.side}/{self.name} exited at startup: {self.process.returncode}')
            return self.dns()
        wait(ready, 'DNS startup')
        self.client = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.client.setsockopt(socket.SOL_SOCKET, socket.SO_BROADCAST, 1)
        self.client.setsockopt(socket.SOL_SOCKET, socket.SO_BINDTODEVICE, b'lo\0')
        self.client.bind(('0.0.0.0', 68)); self.client.settimeout(3)
        self.descendants.update(children(self.process.pid))

    def dns(self):
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as endpoint:
            endpoint.settimeout(.1)
            endpoint.sendto(query('helper.test', 1), ('127.0.0.1', 15353))
            response = semantics(endpoint.recv(4096))
        response.pop('id', None)
        return response

    def exchange(self, kind, address=None, selecting=False, client=1, hostname=None, reboot=False):
        self.xid += 1
        request = bytearray(packet(kind, self.xid, client, address, selecting))
        if hostname is not None:
            # Replace the stock hostname option without relying on Rust parsing.
            opts, pos = bytearray(), 240
            while pos < len(request) and request[pos] != 255:
                code, length = request[pos], request[pos + 1]
                value = request[pos + 2:pos + 2 + length]; pos += length + 2
                if code != 12:
                    opts.extend([code, length]); opts.extend(value)
            opts.extend([12, len(hostname)]); opts.extend(hostname)
            request = request[:240] + opts + b'\xff'
        if kind in (1, 3):
            # Binary delimiters and '=' exercise C's extradata conversion;
            # user class uses RFC3004 counted strings, C rewrites them for helper.
            cpe = b'\x01\x06a1b2c3\x02\x06serial\x03\x05class'
            agent = b'\x01\x07circuit\x02\x06remote\x06\x0asubscriber'
            extras = [(60, b'vendor=ignored'), (77, b'\x03one\x03two'),
                      (161, b'https://mud.test/device'), (82, agent),
                      (125, struct.pack('!IB', 3561, len(cpe)) + cpe)]
            request.pop()
            for code, value in extras:
                request.extend([code, len(value)]); request.extend(value)
            request.append(255)
        if reboot:
            request[12:16] = b'\0' * 4
            request[-1:] = bytes([50, 4]) + socket.inet_aton(address) + b'\xff'
        destination = '255.255.255.255' if kind == 1 or selecting or reboot else '127.0.0.1'
        started = time.monotonic()
        self.client.sendto(request, (destination, 67))
        (self.out / f'{self.side}-{self.name}-{self.xid}.request').write_bytes(request)
        if kind == 7:
            return None
        answer = self.client.recv(16384)
        options = decode(answer, self.xid)
        (self.out / f'{self.side}-{self.name}-{self.xid}.reply').write_bytes(answer)
        if options.get(53) != bytes([2 if kind == 1 else 5]):
            raise AssertionError('unexpected DHCP response')
        elapsed = time.monotonic() - started
        return socket.inet_ntoa(answer[16:20]), elapsed

    def dora(self, client=1):
        address, _ = self.exchange(1, client=client)
        self.exchange(3, address, True, client=client)
        return address

    def stage(self, name, count=None):
        if count is not None:
            wait(lambda: len(capture(self.events)) >= count, name)
        time.sleep(.08)
        rows = capture(self.events)
        self.stages.append({'name': name, 'records': normalized(rows, self.start_epoch, time.time())})
        self.raw = rows
        return len(rows)

    def stop(self):
        result = {'forced': False, 'exit': None, 'remaining': [], 'pid_removed': True}
        if self.process is not None:
            self.descendants.update(children(self.process.pid))
            if self.process.poll() is None:
                self.process.terminate()
                try:
                    self.process.wait(8)
                except subprocess.TimeoutExpired:
                    result['forced'] = True
                    os.killpg(self.process.pid, signal.SIGKILL); self.process.wait(3)
            result['exit'] = self.process.returncode
            # C closes helper's input and returns without waiting for its final
            # script. Allow completion, reap only our now-adopted descendants.
            deadline = time.monotonic() + 5
            while time.monotonic() < deadline:
                for pid in self.descendants:
                    try: os.waitpid(pid, os.WNOHANG)
                    except (ChildProcessError, ProcessLookupError): pass
                remaining = [pid for pid in self.descendants if Path(f'/proc/{pid}').exists()]
                if not remaining: break
                time.sleep(.01)
            result['remaining'] = remaining
            if remaining:
                result['forced'] = True
                for pid in remaining:
                    try: os.kill(pid, signal.SIGKILL)
                    except ProcessLookupError: pass
            result['pid_removed'] = not (self.folder / 'pid').exists()
        if self.client: self.client.close()
        if self.log: self.log.close()
        for proc, log in reversed(self.support):
            owned = children(proc.pid)
            if proc.poll() is None:
                proc.terminate()
                try: proc.wait(3)
                except subprocess.TimeoutExpired:
                    os.killpg(proc.pid, signal.SIGKILL); proc.wait(3)
            for pid in owned:
                try: os.kill(pid, signal.SIGKILL)
                except ProcessLookupError: pass
            log.close()
        if self.name == 'hotplug':
            (self.root / 'etc/hotplug.d/dhcp/00-m5-capture').unlink(missing_ok=True)
        return result



SHUTDOWN_CASES = {'shutdown-pid', 'shutdown-group', 'shutdown-queued', 'shutdown-output',
                  'shutdown-exit', 'shutdown-signal', 'shutdown-exec-error',
                  'shutdown-int', 'shutdown-debug-int'}


def process_snapshot(pids, start):
    result = []
    for pid in sorted(pids):
        try:
            raw = Path(f'/proc/{pid}/stat').read_text()
            fields = raw[raw.rindex(')')+2:].split()
            result.append({'pid': pid, 'ppid': int(fields[1]), 'pgid': int(fields[2]),
                           'sid': int(fields[3]), 'state': fields[0],
                           'observed': time.monotonic()-start,
                           'command': Path(f'/proc/{pid}/cmdline').read_bytes().hex()})
        except (FileNotFoundError, ProcessLookupError):
            pass
    return result


def tftp_completed(runner):
    payload = b'helper-shutdown-evidence'
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as endpoint:
        endpoint.settimeout(1)
        endpoint.sendto(b'\0\1health.bin\0octet\0', ('127.0.0.1', 69))
        reply, peer = endpoint.recvfrom(1024)
        assert reply == b'\0\3\0\1'+payload, 'unexpected TFTP DATA'
        endpoint.sendto(b'\0\4\0\1', peer)
    def released():
        for fd in Path(f'/proc/{runner.process.pid}/fd').iterdir():
            try:
                if os.readlink(fd).endswith('/health.bin'):
                    return False
            except FileNotFoundError:
                pass
        return True
    wait(released, 'TFTP completion queued after final ACK')


def shutdown_observe(runner, case):
    start = time.monotonic()
    parent = runner.process.pid
    owned = children(parent)
    before = process_snapshot(owned, start)
    helpers = [row['pid'] for row in before if row['ppid'] == parent]
    assert len(helpers) == 1, ('expected one helper', before)
    result = {'before_signal': before, 'helper_pid': helpers[0], 'samples': [], 'reaped': {}}
    if case == 'shutdown-int':
        os.kill(parent, signal.SIGINT)
        time.sleep(.1)
        result['nondebug_int_ignored'] = runner.process.poll() is None
        assert result['nondebug_int_ignored'], 'normal-mode SIGINT terminated parent'
    signum = signal.SIGINT if case == 'shutdown-debug-int' else signal.SIGTERM
    group = case in ('shutdown-group', 'shutdown-debug-int')
    result['signal_at'] = time.monotonic()-start
    result['signal'] = signum
    result['group'] = group
    result['pid_existed_before'] = (runner.folder/'pid').exists()
    (os.killpg if group else os.kill)(parent, signum)
    deadline = time.monotonic()+8
    prior = None
    while time.monotonic() < deadline:
        owned.update(children(parent))
        owned.update(children(os.getpid())-{os.getpid()})
        runner.descendants.update(owned)
        if runner.process.poll() is not None and 'parent_exit_at' not in result:
            result['parent_exit_at'] = time.monotonic()-start
            result['parent_exit'] = runner.process.returncode
            result['pid_absent_at_parent_exit'] = not (runner.folder/'pid').exists()
        if (runner.events/'1.done').exists() and 'first_script_done_at' not in result:
            result['first_script_done_at'] = time.monotonic()-start
        for pid in owned-{parent}:
            try:
                reaped, status = os.waitpid(pid, os.WNOHANG)
                if reaped:
                    result['reaped'][str(reaped)] = status
            except (ChildProcessError, ProcessLookupError):
                pass
        snapshot = process_snapshot(owned, start)
        key = [(row['pid'], row['ppid'], row['state']) for row in snapshot]
        if key != prior:
            result['samples'].append({'at': time.monotonic()-start, 'processes': snapshot})
            prior = key
        if runner.process.poll() is not None and not snapshot:
            break
        time.sleep(.005)
    result['remaining'] = process_snapshot(owned, start)
    result['helper_status'] = result['reaped'].get(str(helpers[0]))
    result['parent_seconds'] = result.get('parent_exit_at', time.monotonic()-start)-result['signal_at']
    return result


def shutdown_errors(row):
    observation = row.get('shutdown_observation', {})
    errors = []
    expected_exit = 5 if row['case'] == 'shutdown-debug-int' else 0
    if observation.get('parent_exit') != expected_exit:
        errors.append('parent-exit')
    if not 0 <= observation.get('parent_seconds', 99) < .75:
        errors.append('parent-waited-for-script')
    if observation.get('parent_exit_at', 99) >= observation.get('first_script_done_at', -1):
        errors.append('parent-did-not-exit-before-script')
    if not observation.get('pid_absent_at_parent_exit'):
        errors.append('pid-file-survived-parent')
    if observation.get('helper_status') != 0 or observation.get('remaining'):
        errors.append('helper-exit-or-process-leak')
    if row['case'] == 'shutdown-int' and not observation.get('nondebug_int_ignored'):
        errors.append('normal-int-not-ignored')
    expected_records = 1 if row['case'] == 'shutdown-exec-error' else 3
    if len(row.get('raw', [])) != expected_records:
        errors.append('queued-callback-loss')
    return errors


def run_shutdown_case(root, side, out, case):
    data = root/'m2/helper-shutdown-data'; data.mkdir(exist_ok=True)
    (data/'health.bin').write_bytes(b'helper-shutdown-evidence')
    env = {'M5_SLOW': '1', 'M5_SLOW_SECONDS': '3'}
    if case == 'shutdown-output': env['M5_LATE_OUTPUT'] = '1'
    if case == 'shutdown-exit': env['M5_EXIT'] = '1'
    if case == 'shutdown-signal': env['M5_SIGNAL'] = '1'
    if case == 'shutdown-exec-error': env['M5_REMOVE_SCRIPT'] = '1'
    runner = Side(root, side, out, case, ['enable-tftp', 'tftp-root=/m2/helper-shutdown-data'], env,
                  debug=case == 'shutdown-debug-int')
    result = {'case': case, 'side': side, 'status': 'failed'}
    try:
        runner.start()
        result['daemon_identity'] = process_identity(root, runner.process.pid)
        if case == 'shutdown-queued':
            runner.dora(1)
        else:
            tftp_completed(runner)
        wait(lambda: (runner.events/'slow-ready').exists(), 'first callback sleeping')
        if case == 'shutdown-queued':
            tftp_completed(runner)
            runner.dora(2)
        else:
            runner.dora(1)
            tftp_completed(runner)
        # Ensure both ordinary owner turns consumed accepted network work;
        # script1 remains asleep for the independently checked parent boundary.
        runner.dns(); time.sleep(.05)
        result['shutdown_observation'] = shutdown_observe(runner, case)
        result['raw'] = capture(runner.events)
        runner.stage('callbacks-after-parent-exit', 1 if case == 'shutdown-exec-error' else 3)
        result['stages'] = runner.stages
        errors = shutdown_errors(result)
        if errors: raise AssertionError(errors)
        result['status'] = 'passed'
    except Exception as error:
        result['error'] = f'{type(error).__name__}: {error}'
        result['traceback'] = traceback.format_exc()
    finally:
        result['raw'] = capture(runner.events)
        result['stages'] = runner.stages
        result['cleanup'] = runner.stop()
        expected = {'forced': False, 'exit': 5 if case == 'shutdown-debug-int' else 0,
                    'remaining': [], 'pid_removed': True}
        if result['cleanup'] != expected: result['status'] = 'failed'
        write_json(out/f'{side}-{case}.json', result)
    return result


def run_case(root, side, out, case):
    if case in SHUTDOWN_CASES:
        return run_shutdown_case(root, side, out, case)
    flags, env, debug = [], {}, False
    if case == 'renewal': flags.append('script-on-renewal')
    if case == 'scriptuser': flags.append('dhcp-scriptuser=nobody')
    if case == 'scriptuser-debug': flags.append('dhcp-scriptuser=nobody'); debug = True
    if case in ('slow', 'shutdown'): env['M5_SLOW'] = '1'
    if case == 'exit': env['M5_EXIT'] = '1'
    if case == 'signal': env['M5_SIGNAL'] = '1'
    if case in ('readonly', 'init-exit', 'slow-init', 'init-capacity'): flags.append('leasefile-ro')
    if case == 'slow-init': env['M5_SLOW_INIT'] = '1'
    if case == 'init-capacity': flags.append('dhcp-lease-max=1')
    if case == 'init-exit': env['M5_INIT_STATUS'] = '7'
    if case == 'unknown-user': flags.append('dhcp-scriptuser=m5-no-such-user-19375')
    runner = Side(root, side, out, case, flags, env, debug)
    if case in ('readonly', 'init-exit', 'slow-init', 'init-capacity'):
        contents = '0 02:00:00:00:00:09 127.0.0.19 restored *\n'
        if case == 'init-capacity': contents += '0 02:00:00:00:00:08 127.0.0.18 overflow *\n'
        (runner.events / 'init.leases').write_text(contents)
    if case == 'missing-exec': runner.script.unlink()
    result = {'case': case, 'side': side, 'status': 'failed'}
    try:
        if case in ('unknown-user', 'init-exit', 'init-capacity'):
            runner.log = (out / f'{side}-{case}.log').open('wb')
            runner.process = subprocess.Popen(command(root, side, '--keep-in-foreground', '--conf-file=' + runner.inside + '/config'), env=runner.env, stdout=runner.log, stderr=runner.log, start_new_session=True)
            deadline = time.monotonic() + 5
            while runner.process.poll() is None:
                runner.descendants.update(children(runner.process.pid))
                if time.monotonic() >= deadline:
                    raise AssertionError('startup failure did not exit')
                time.sleep(.005)
            # This isolated PID-namespace driver adopts fast-exiting helper
            # children; they must be reaped and checked just like live ones.
            runner.descendants.update(children(os.getpid()) - {os.getpid()})
            result['startup_exit'] = runner.process.returncode
            expected = {'unknown-user': 1, 'init-exit': 17, 'init-capacity': 5}[case]
            if result['startup_exit'] != expected:
                raise AssertionError(f'expected startup exit {expected}, got {result["startup_exit"]}')
            result['status'] = 'passed'
            result['stages'] = []
            return result
        runner.start()
        if case in ('readonly', 'slow-init'):
            runner.stage('restored-old', 2)
            if case == 'slow-init': result['init_dns_latency'] = runner.init_dns_latency
        address = runner.dora()
        if case == 'helper-death':
            runner.stage('add-before-helper-death', 1)
            owned = children(runner.process.pid) - {runner.process.pid}
            wait(lambda: len(children(runner.process.pid) - {runner.process.pid}) == 1, 'one idle helper')
            helper_pid = next(iter(children(runner.process.pid) - {runner.process.pid}))
            runner.descendants.add(helper_pid)
            os.kill(helper_pid, signal.SIGKILL)
            time.sleep(.05)
            runner.dora(2)
            result['dns_after_script'] = runner.dns()
            runner.stage('no-second-script-after-helper-death')
            if len(runner.raw) != 1: raise AssertionError('unexpected script after helper death')
        elif case == 'missing-exec':
            time.sleep(.2)
            result['dns_after_script'] = runner.dns()
            if capture(runner.events): raise AssertionError('missing executable generated a script capture')
            runner.stage('missing-exec-no-event')
        elif case == 'shutdown':
            wait(lambda: (runner.events / 'slow-ready').exists(), 'script sleeping before SIGTERM')
            runner.dora(2)
            runner.stop()
            runner.stage('queued-callbacks-after-sigterm', 2)
        elif case == 'slow':
            wait(lambda: (runner.events / 'slow-ready').exists(), 'script sleeping')
            start = time.monotonic(); runner.dns(); dns_elapsed = time.monotonic() - start
            start = time.monotonic(); runner.dora(2); dora_elapsed = time.monotonic() - start
            result['latency'] = {'dns_seconds': dns_elapsed, 'dora_seconds': dora_elapsed}
            if dns_elapsed >= 1 or dora_elapsed >= 1:
                raise AssertionError('script blocked service owner')
            runner.stage('two-adds-after-slow-script', 2)
        elif case in ('scriptuser', 'scriptuser-debug', 'exit', 'signal', 'readonly', 'slow-init', 'hotplug'):
            runner.stage('add', 3 if case in ('readonly', 'slow-init') else 1)
            result['dns_after_script'] = runner.dns()
            if case == 'hotplug':
                wait(lambda: runner.hotplug_events(), 'actual hotplug bus handler')
                result['hotplug_events'] = runner.hotplug_events()
        else:
            count = runner.stage('add', 1)
            time.sleep(1.05)
            runner.exchange(3, address)
            count = runner.stage('renewal', count + 1 if case == 'renewal' else None)
            runner.exchange(3, address, hostname=b'renamed')
            count = runner.stage('name-change', count + 2)
            runner.exchange(3, address, hostname=b'renamed', reboot=True)
            count = runner.stage('init-reboot-refreshes-extradata', count + 1)
            runner.process.send_signal(signal.SIGHUP)
            count = runner.stage('sighup', count + 1)
            runner.exchange(7, address)
            runner.stage('release', count + 1)
        result['stages'] = runner.stages
        result['raw'] = runner.raw
        result['status'] = 'passed'
    except Exception as error:
        result['error'] = f'{type(error).__name__}: {error}'
        result['traceback'] = traceback.format_exc()
    finally:
        result['raw'] = capture(runner.events)
        result['stages'] = runner.stages
        result['cleanup'] = runner.stop()
        expected_cleanup = {'forced': False, 'exit': {'unknown-user': 1, 'init-exit': 17, 'init-capacity': 5}.get(case, 0), 'remaining': [], 'pid_removed': True}
        if result['cleanup'] != expected_cleanup:
            result['status'] = 'failed'
        write_json(out / f'{side}-{case}.json', result)
    return result


def compare(rows, expected_cases=None):
    errors = []
    cases = set(expected_cases) if expected_cases is not None else {row['case'] for row in rows}
    if any(row['case'] not in cases for row in rows): errors.append('unexpected scenario')
    for case in sorted(cases):
        sides = [row for row in rows if row['case'] == case]
        if sorted(row['side'] for row in sides) != ['c', 'rust']:
            errors.append(f'{case}: missing or duplicate side'); continue
        c = next(row for row in sides if row['side'] == 'c')
        rust = next(row for row in sides if row['side'] == 'rust')
        if c['status'] != 'passed' or rust['status'] != 'passed':
            errors.append(f'{case}: unexecuted/failed stage'); continue
        expected_exit = {'unknown-user': 1, 'init-exit': 17, 'init-capacity': 5, 'shutdown-debug-int': 5}.get(case, 0)
        for row in (c, rust):
            if case in SHUTDOWN_CASES:
                errors.extend(f'{case}: {error}' for error in shutdown_errors(row))
            cleanup = row.get('cleanup')
            if cleanup != {'forced': False, 'exit': expected_exit, 'remaining': [], 'pid_removed': True}:
                errors.append(f'{case}: missing or failed cleanup')
        for field in ('stages', 'cleanup', 'dns_after_script', 'hotplug_events', 'startup_exit'):
            if c.get(field) != rust.get(field): errors.append(f'{case}: {field} differ')
    return errors


def controls(rows):
    expected = {row['case'] for row in rows}
    def populated(values):
        return next((row for row in values if row['side'] == 'rust' and row.get('stages') and row['stages'][0]['records']), None)
    changed = copy.deepcopy(rows)
    row = populated(changed)
    if row:
        row['stages'][0]['records'][0]['uid'] ^= 1
    else:
        next(row for row in changed if row['side'] == 'rust')['status'] = 'failed'
    identity = bool(compare(changed, expected))
    changed = copy.deepcopy(rows)
    row = populated(changed)
    if row:
        row['stages'][0]['records'][0]['env']['DNSMASQ_INTERFACE'] = b'wrong-interface'.hex()
    else:
        next(row for row in changed if row['side'] == 'rust')['cleanup']['forced'] = True
    environment = bool(compare(changed, expected))
    changed = copy.deepcopy(rows)
    stage = next((stage for row in changed if row['side'] == 'rust' for stage in row.get('stages', [])
                  if any(value != stage['records'][0] for value in stage['records'][1:])), None)
    if stage:
        # A TFTP/lease/TFTP sequence is a palindrome. Swap two distinct
        # records so this control always changes the observed order.
        records = stage['records']
        index = next(i for i, value in enumerate(records[1:], 1) if value != records[0])
        records[0], records[index] = records[index], records[0]
    else:
        next(row for row in changed if row['side'] == 'rust')['side'] = 'c'
    ordering = bool(compare(changed, expected))
    missing = [row for row in rows if row['case'] != next(iter(expected))]
    startup = copy.deepcopy(rows)
    for row in startup:
        if row['case'] in ('unknown-user', 'init-exit', 'init-capacity'):
            row.pop('cleanup', None)
    startup_detected = bool(compare(startup, expected)) if any(row['case'] in ('unknown-user', 'init-exit', 'init-capacity') for row in rows) else True
    extra = {}
    if any(row['case'] in SHUTDOWN_CASES for row in rows):
        for name, field, value in [('delayed-parent', 'parent_seconds', 9), ('script-before-parent', 'first_script_done_at', -1), ('helper-failure', 'helper_status', 5)]:
            changed = copy.deepcopy(rows)
            next(row for row in changed if row['side'] == 'rust' and row['case'] in SHUTDOWN_CASES)['shutdown_observation'][field] = value
            extra[name] = bool(compare(changed, expected))
    return {**extra, 'missing-startup-cleanup-both-sides': startup_detected, 'changed-credentials-or-status': identity, 'changed-environment-or-cleanup': environment,
            'changed-order-or-duplicate-side': ordering, 'missing-whole-scenario': bool(compare(missing, expected))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image-root', type=Path, required=True)
    parser.add_argument('--rust', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--side', choices=('both', 'c', 'rust'), default='both')
    parser.add_argument('--cases', default='lifecycle,renewal,scriptuser,scriptuser-debug,slow,exit,signal,readonly,hotplug,missing-exec,unknown-user,init-exit,helper-death,slow-init,init-capacity,shutdown')
    args = parser.parse_args()
    if os.geteuid() != 0 or os.environ.get('DNSMASQ_TEST_ISOLATED') != '1':
        parser.error('root under run_isolated.sh required')
    if sorted(name for _, name in socket.if_nameindex()) != ['lo']:
        parser.error('isolated loopback namespace required')
    out = args.out.resolve()
    if out.exists() or 'private' not in out.parts:
        parser.error('fresh evidence output under private/ required')
    root = prepare(args.image_root, None, out, args.rust)
    rows = []
    for case in args.cases.split(','):
        if case not in SHUTDOWN_CASES and case not in ('lifecycle', 'renewal', 'scriptuser', 'scriptuser-debug', 'slow', 'exit', 'signal', 'readonly', 'hotplug', 'missing-exec', 'unknown-user', 'init-exit', 'helper-death', 'slow-init', 'init-capacity', 'shutdown'):
            parser.error('unknown case ' + case)
        for side in (('c', 'rust') if args.side == 'both' else (args.side,)):
            rows.append(run_case(root, side, out, case))
    failures = compare(rows, args.cases.split(',')) if args.side == 'both' else [f"{r['case']}: {r.get('error', 'cleanup failed')}" for r in rows if r['status'] != 'passed']
    negative = controls(rows) if args.side == 'both' and not failures else {'not-run': False}
    result = {'passed': not failures and (args.side != 'both' or all(negative.values())),
              'comparison_executed': args.side == 'both', 'requested_cases': args.cases.split(','),
              'c_sha256': STOCK_SHA256, 'rust_sha256': sha256(args.rust),
              'failures': failures, 'negative_controls': negative,
              'cases': rows, 'scope': 'helper family incl image dhcp-script.sh/hotplug and DHCP/TFTP shutdown ownership; requested cases and raw records retained'}
    write_json(out / 'result.json', result)
    print(json.dumps({k: result[k] for k in ('passed', 'failures', 'negative_controls')}))
    return 0 if result['passed'] else 1


if __name__ == '__main__':
    raise SystemExit(main())
