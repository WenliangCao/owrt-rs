#!/usr/bin/env python3
"""Isolated DNS service reference/calibration probe (not a benchmark).

The full schedule includes UDP/TCP, IPv4/IPv6, unknown records and negative
caching; a partial Rust service may not support all cases yet. Run through
run_isolated.sh on Linux. A C result is the comparison reference, never an
expectation generated by Rust. --inject-failure calibrates error accounting.
"""
import argparse
import collections
import ipaddress
import json
import os
from pathlib import Path
import signal
import socket
import struct
import subprocess
import threading
import time


def name(value):
    return b"".join(bytes([len(part)]) + part.encode("ascii") for part in value.split(".")) + b"\0"


def read_name(packet, pos):
    labels, visited, resume = [], set(), None
    while True:
        if pos >= len(packet) or pos in visited:
            raise ValueError("invalid compression")
        visited.add(pos)
        size = packet[pos]
        pos += 1
        if size == 0:
            return b".".join(labels).decode("ascii").lower(), resume or pos
        if size & 0xc0 == 0xc0:
            if pos >= len(packet):
                raise ValueError("truncated pointer")
            resume = resume or pos + 1
            pos = ((size & 63) << 8) | packet[pos]
        elif size <= 63 and pos + size <= len(packet):
            labels.append(packet[pos:pos + size])
            pos += size
        else:
            raise ValueError("invalid label")


def rr(rrtype, value, ttl=120, owner=b"\xc0\x0c"):
    return owner + struct.pack("!HHIH", rrtype, 1, ttl, len(value)) + value


def query(host, kind=1, ident=0x2930):
    return struct.pack("!6H", ident, 0x0100, 1, 0, 0, 0) + name(host) + struct.pack("!HH", kind, 1)


def answer(packet):
    host, end = read_name(packet, 12)
    kind, _ = struct.unpack_from("!HH", packet, end)
    question = packet[12:end + 4]
    flags, answers, authority, body = 0x8180, 1, 0, b""
    if host.startswith("nx.") or host.startswith("nodata."):
        flags |= 3 if host.startswith("nx.") else 0
        answers, authority = 0, 1
        soa = name("ns.test") + name("admin.test") + struct.pack("!5I", 1, 60, 60, 600, 30)
        body = rr(6, soa, 30, name("test"))
    elif kind == 1:
        body = rr(1, ipaddress.ip_address("192.0.2.7").packed)
    elif kind == 28:
        body = rr(28, ipaddress.ip_address("2001:db8::7").packed)
    elif kind == 16:
        body = rr(16, b"\x05hello")
    elif kind == 5:
        body = rr(5, name("target.test"))
    else:
        body = rr(kind, b"\x00\xff\xc0\x0c")
    return packet[:2] + struct.pack("!5H", flags, 1, answers, authority, 0) + question + body


def semantics(packet):
    if len(packet) < 12:
        raise ValueError("short header")
    ident, flags, qd, an, ns, ar = struct.unpack_from("!6H", packet)
    pos, questions, records = 12, [], []
    for _ in range(qd):
        host, pos = read_name(packet, pos)
        kind, cls = struct.unpack_from("!HH", packet, pos)
        pos += 4
        questions.append([host, kind, cls])
    for section, count in (("answer", an), ("authority", ns), ("additional", ar)):
        for _ in range(count):
            host, pos = read_name(packet, pos)
            kind, cls, ttl, size = struct.unpack_from("!HHIH", packet, pos)
            pos += 10
            end = pos + size
            if end > len(packet):
                raise ValueError("short RDATA")
            if kind in (2, 5, 12):
                data = read_name(packet, pos)[0]
            elif kind in (1, 28):
                data = str(ipaddress.ip_address(packet[pos:end]))
            elif kind == 6:
                mname, p = read_name(packet, pos)
                rname, p = read_name(packet, p)
                data = [mname, rname, *struct.unpack_from("!5I", packet, p)]
            else:
                data = packet[pos:end].hex()
            records.append({"section":section, "name":host, "type":kind, "class":cls, "ttl":ttl, "data":data})
            pos = end
    return {"id":ident, "flags":flags, "questions":questions, "records":records}


def exact_read(connection, count):
    out = bytearray()
    while len(out) < count:
        value = connection.recv(count - len(out))
        if not value:
            raise ConnectionError("short TCP frame")
        out.extend(value)
    return bytes(out)


class Upstream:
    def __init__(self, inject_failure=False):
        self.socket = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.socket.bind(("127.0.0.1", 0))
        self.socket.settimeout(.1)
        self.port = self.socket.getsockname()[1]
        self.counts = collections.Counter()
        self.failures = []
        self.inject_failure = inject_failure
        self.stop = threading.Event()
        self.thread = threading.Thread(target=self.run)
        self.thread.start()

    def run(self):
        while not self.stop.is_set():
            try:
                packet, peer = self.socket.recvfrom(65535)
            except socket.timeout:
                continue
            try:
                host, end = read_name(packet, 12)
                kind = struct.unpack_from("!H", packet, end)[0]
                self.counts[(host, kind)] += 1
                response = answer(packet)
                if self.inject_failure and host == "unknown.test":
                    # A controlled SERVFAIL must become a counted test failure,
                    # not silently disappear from the denominator.
                    response = packet[:2] + struct.pack("!5H",0x8182,1,0,0,0) + packet[12:end+4]
                self.socket.sendto(response, peer)
            except Exception as error:
                self.failures.append(repr(error))

    def close(self):
        self.stop.set()
        self.thread.join(timeout=2)
        self.socket.close()
        if self.thread.is_alive():
            raise RuntimeError("upstream thread leaked")


def exchange(port, packet, tcp=False, ipv6=False):
    family = socket.AF_INET6 if ipv6 else socket.AF_INET
    with socket.socket(family, socket.SOCK_STREAM if tcp else socket.SOCK_DGRAM) as conn:
        conn.settimeout(2)
        conn.connect(("::1" if ipv6 else "127.0.0.1", port))
        if tcp:
            conn.sendall(struct.pack("!H", len(packet)) + packet)
            return exact_read(conn, struct.unpack("!H", exact_read(conn, 2))[0])
        conn.send(packet)
        return conn.recv(65535)


def compare(reference, actual):
    # This smoke suite has no unordered RRset, clock-advanced query, or random ID.
    # Keep flags, TTL, order and upstream-count changes visible.
    return reference == actual


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--binary", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--reference", type=Path)
    ap.add_argument("--inject-failure", action="store_true", help="calibration: expected 11 successes, 1 error, exit 1")
    args = ap.parse_args()
    # sysfs may retain the host's network view across unshare; if_nameindex
    # queries this process's network namespace directly.
    if os.environ.get("DNSMASQ_TEST_ISOLATED") != "1" or sorted(n for _, n in socket.if_nameindex()) != ["lo"]:
        ap.error("refusing to start listeners outside dedicated loopback-only namespace")
    if args.out.exists():
        ap.error("choose a new output directory")
    args.out.mkdir(parents=True)
    # Calibrate semantic parser and comparator using known independent fixtures.
    fixture = semantics(answer(query("calibration.test")))
    assert fixture["records"][0]["data"] == "192.0.2.7"
    assert compare(fixture, fixture.copy())
    assert not compare(fixture, fixture | {"flags":0})
    upstream = Upstream(args.inject_failure)
    with socket.socket() as reserve:
        reserve.bind(("127.0.0.1", 0))
        port = reserve.getsockname()[1]
    config = args.out / "dnsmasq.conf"
    config.write_text(f"port={port}\nno-resolv\nno-hosts\nbind-interfaces\nlisten-address=127.0.0.1,::1\n"
                      f"server=127.0.0.1#{upstream.port}\ncache-size=1000\nedns-packet-max=1232\n"
                      f"pid-file={args.out}/pid\nlog-facility={args.out}/daemon.log\nuser=root\n")
    errors, cases = [], []
    log = (args.out / "stderr.log").open("wb")
    process = subprocess.Popen([str(args.binary.resolve()), "-k", "-C", str(config.resolve())], stdout=log, stderr=log, start_new_session=True)
    try:
        for _ in range(100):
            if process.poll() is not None:
                raise RuntimeError(f"daemon exited {process.returncode}")
            try:
                exchange(port, query("ready.test"))
                break
            except (ConnectionError, OSError):
                time.sleep(.01)
        else:
            raise RuntimeError("daemon never ready")
        schedule = [("a.test", 1, False, False), ("a.test", 1, False, False),
                    ("aaaa.test", 28, False, True), ("txt.test", 16, False, False),
                    ("cname.test", 5, False, False), ("unknown.test", 65400, False, False),
                    ("nx.test", 1, False, False), ("nx.test", 1, False, False),
                    ("nodata.test", 28, False, False), ("nodata.test", 28, False, False),
                    ("a.test", 1, True, False), ("aaaa.test", 28, True, True)]
        for host, kind, tcp, ipv6 in schedule:
            try:
                response = exchange(port, query(host, kind), tcp, ipv6)
                parsed = semantics(response)
                if parsed["id"] != 0x2930 or parsed["questions"] != [[host, kind, 1]]:
                    raise ValueError("ID or question mismatch")
                if parsed["flags"] & 15 != (3 if host == "nx.test" else 0):
                    raise ValueError("unexpected response code")
                cases.append({"host":host, "type":kind, "tcp":tcp, "ipv6":ipv6,
                              "response":parsed, "upstream_queries":upstream.counts[(host, kind)]})
            except Exception as error:
                errors.append({"host":host, "type":kind, "error":repr(error)})
        if upstream.failures:
            errors.extend({"upstream_error":e} for e in upstream.failures)
    finally:
        try:
            os.killpg(process.pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        try:
            process.wait(timeout=3)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)
            process.wait()
            errors.append({"shutdown":"required SIGKILL"})
        upstream.close()
        log.close()
    if args.reference:
        reference = json.loads(args.reference.read_text())
        if not compare(reference["cases"], cases):
            errors.append({"differential":"semantic or side-effect mismatch"})
    report = {"planned":12, "success":len(cases), "errors":errors, "cases":cases,
              "daemon_exit":process.returncode, "calibration":"positive and deliberate mismatch passed",
              "scope":"DNS smoke baseline; not full correctness or performance acceptance"}
    (args.out / "result.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"success":len(cases), "errors":len(errors), "output":str(args.out / "result.json")}))
    raise SystemExit(bool(errors) or len(cases) != 12)


if __name__ == "__main__":
    main()
