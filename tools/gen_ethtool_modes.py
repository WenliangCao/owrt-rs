#!/usr/bin/env python3
"""Generate components/netifd/src/ethtool_modes.rs.

netifd builds its mode table at compile time with make_ethtool_modes_h.sh,
whose ordering inside one speed comes out of a `sort -g` pipeline and is not
alphabetical. `network.device status` reports the modes in that order, so the
order is taken from the generator's own output rather than re-derived:

  # on a host with the OpenWrt SDK for this target
  CC=.../aarch64-openwrt-linux-gcc
  sh netifd/make_ethtool_modes_h.sh "$CC" > ethtool-modes.h

  python3 tools/gen_ethtool_modes.py ethtool-modes.h linux/ethtool.h \
      > components/netifd/src/ethtool_modes.rs

The second argument is the same toolchain's <linux/ethtool.h>, which supplies
the numeric bit indices the enum names stand for.
"""
import re
import sys

modes_h = open(sys.argv[1]).read()
ethtool_h = open(sys.argv[2]).read()

body = re.search(r'enum ethtool_link_mode_bit_indices \{(.*?)\n\};', ethtool_h, re.S).group(1)
bits = {}
nxt = 0
for name, val in re.findall(r'(ETHTOOL_LINK_MODE_\w+)\s*(?:=\s*(\d+))?', body):
    nxt = int(val) if val else nxt
    bits[name] = nxt
    nxt += 1


def bit(speed, mode, duplex):
    return bits[f'ETHTOOL_LINK_MODE_{speed}base{mode}_{duplex}_BIT']


rows = []
for kind, speed, mode in re.findall(
    r'ETHTOOL_MODE_(FULL|HALF|BOTH)\((\d+),\s*([A-Za-z0-9]+)\)', modes_h
):
    half = bit(speed, mode, 'Half') if kind in ('HALF', 'BOTH') else -1
    full = bit(speed, mode, 'Full') if kind in ('FULL', 'BOTH') else -1
    rows.append((int(speed), half, full, f'{speed}base{mode}'))

print('// @generated by tools/gen_ethtool_modes.py from the OpenWrt 25.12.5')
print('// aarch64 toolchain. Do not edit by hand.')
print('//')
print('// The same table netifd generates at build time: the names, and the')
print('// order `network.device status` reports them in.')
print()
print('/// (speed, half-duplex bit or -1, full-duplex bit or -1, name)')
print('pub const ETHTOOL_MODES: &[(u32, i32, i32, &str)] = &[')
for speed, half, full, name in rows:
    print(f'    ({speed}, {half}, {full}, "{name}"),')
print('];')
print()
print(f'pub const ETHTOOL_LINK_MODE_PAUSE_BIT: i32 = {bits["ETHTOOL_LINK_MODE_Pause_BIT"]};')
print('pub const ETHTOOL_LINK_MODE_ASYM_PAUSE_BIT: i32 = '
      f'{bits["ETHTOOL_LINK_MODE_Asym_Pause_BIT"]};')
